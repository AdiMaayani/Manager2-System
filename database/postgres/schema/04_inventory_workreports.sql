-- ---------------------------------------------------------------------
-- InventoryItems
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "InventoryItems" (
    "InventoryItemId"     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SkuCode"             varchar(50)  NOT NULL,
    "ItemName"            varchar(200) NOT NULL,
    "Category"            varchar(100) NULL,
    "QuantityOnHand"      numeric(18, 3) NOT NULL DEFAULT 0,
    "Unit"                varchar(20)  NOT NULL,
    "MinimumQuantity"     numeric(18, 3) NULL,
    "LocationName"        varchar(200) NULL,
    "Notes"               varchar(500) NULL,
    "IsActive"            boolean NOT NULL DEFAULT true,
    "CreatedAt"           timestamp(6) NOT NULL DEFAULT (now() at time zone 'utc'),
    "UpdatedAt"           timestamp(6) NULL,
    "DeletedAt"           timestamp(6) NULL,
    "ImagePath"           varchar(260) NULL,
    "ImageContentType"    varchar(100) NULL,
    "ImageFileSizeBytes"  bigint NULL,
    CONSTRAINT "CK_InventoryItems_SkuCode_NotBlank" CHECK (length(btrim("SkuCode")) > 0),
    CONSTRAINT "CK_InventoryItems_ItemName_NotBlank" CHECK (length(btrim("ItemName")) > 0),
    CONSTRAINT "CK_InventoryItems_QuantityOnHand_NonNegative" CHECK ("QuantityOnHand" >= 0),
    CONSTRAINT "CK_InventoryItems_Unit_NotBlank" CHECK (length(btrim("Unit")) > 0),
    CONSTRAINT "CK_InventoryItems_MinimumQuantity_NonNegative" CHECK ("MinimumQuantity" IS NULL OR "MinimumQuantity" >= 0),
    CONSTRAINT "CK_InventoryItems_ImageFileSizeBytes_NonNegative" CHECK ("ImageFileSizeBytes" IS NULL OR "ImageFileSizeBytes" >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_InventoryItems_SkuCode_Active"
    ON "InventoryItems" ("SkuCode")
    WHERE ("IsActive" = true);
CREATE INDEX IF NOT EXISTS "IX_InventoryItems_IsActive_ItemName"
    ON "InventoryItems" ("IsActive", "ItemName", "InventoryItemId");
CREATE INDEX IF NOT EXISTS "IX_InventoryItems_Category_IsActive"
    ON "InventoryItems" ("Category", "IsActive");

-- ---------------------------------------------------------------------
-- WorkReports
--   Status default preserves the Hebrew business workflow value (draft).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "WorkReports" (
    "WorkReportId"        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkItemId"          integer NULL,
    "ReportType"          varchar(50)  NULL,
    "ReportDate"          timestamp(3) NULL,
    "ProjectName"         varchar(150) NULL,
    "CustomerName"        varchar(150) NULL,
    "Site"                varchar(200) NULL,
    "StartTime"           varchar(10)  NULL,
    "EndTime"             varchar(10)  NULL,
    "Summary"             varchar(1000) NULL,
    "Notes"               varchar(2000) NULL,
    "ReporterEmployeeId"  integer NULL,
    "ReporterName"        varchar(100) NULL,
    "ReporterRole"        varchar(100) NULL,
    "WorkersCount"        integer NULL DEFAULT 0,
    "FollowUpRequired"    boolean NULL DEFAULT false,
    "FollowUpReason"      varchar(1000) NULL,
    "CreatedAt"           timestamp(3) NULL DEFAULT localtimestamp,
    "Status"              varchar(50)  NOT NULL DEFAULT 'טיוטה',
    -- Independent report lifecycle (2026-06-19 overhaul). Status stays the Hebrew workflow status;
    -- LifecycleStatus separately controls Draft/Finalized/Reversed and inventory finalization.
    "LifecycleStatus"     varchar(20)  NOT NULL DEFAULT 'Draft',
    "FinalizedAt"         timestamp(6) NULL,
    "FinalizedByUserId"   integer NULL,
    "ReversedAt"          timestamp(6) NULL,
    "ReversedByUserId"    integer NULL,
    "ReversalReason"      varchar(500) NULL,
    "AmendsWorkReportId"  integer NULL,
    "UpdatedAt"           timestamp(6) NULL,
    "UpdatedByUserId"     integer NULL,
    CONSTRAINT "FK_WorkReports_WorkItems" FOREIGN KEY ("WorkItemId") REFERENCES "WorkItems" ("WorkItemId"),
    CONSTRAINT "FK_WorkReports_Employees" FOREIGN KEY ("ReporterEmployeeId") REFERENCES "Employees" ("EmployeeId"),
    CONSTRAINT "FK_WorkReports_FinalizedByUser" FOREIGN KEY ("FinalizedByUserId") REFERENCES "Users" ("UserId"),
    CONSTRAINT "FK_WorkReports_ReversedByUser" FOREIGN KEY ("ReversedByUserId") REFERENCES "Users" ("UserId"),
    CONSTRAINT "FK_WorkReports_UpdatedByUser" FOREIGN KEY ("UpdatedByUserId") REFERENCES "Users" ("UserId"),
    CONSTRAINT "FK_WorkReports_AmendsWorkReport" FOREIGN KEY ("AmendsWorkReportId") REFERENCES "WorkReports" ("WorkReportId"),
    CONSTRAINT "CK_WorkReports_LifecycleStatus" CHECK ("LifecycleStatus" IN ('Draft', 'Finalized', 'Reversed')),
    CONSTRAINT "CK_WorkReports_LifecycleMetadata" CHECK (
        ("LifecycleStatus" IN ('Draft', 'Finalized') AND "ReversedAt" IS NULL AND "ReversedByUserId" IS NULL AND "ReversalReason" IS NULL)
        OR ("LifecycleStatus" = 'Reversed' AND "ReversedAt" IS NOT NULL AND length(btrim("ReversalReason")) > 0)
    ),
    CONSTRAINT "CK_WorkReports_NotSelfAmend" CHECK ("AmendsWorkReportId" IS NULL OR "AmendsWorkReportId" <> "WorkReportId")
);

CREATE INDEX IF NOT EXISTS "IX_WorkReports_LifecycleStatus"
    ON "WorkReports" ("LifecycleStatus", "WorkReportId");
CREATE INDEX IF NOT EXISTS "IX_WorkReports_AmendsWorkReportId"
    ON "WorkReports" ("AmendsWorkReportId")
    WHERE ("AmendsWorkReportId" IS NOT NULL);
CREATE INDEX IF NOT EXISTS "IX_WorkReports_WorkItemId"
    ON "WorkReports" ("WorkItemId")
    WHERE ("WorkItemId" IS NOT NULL);

