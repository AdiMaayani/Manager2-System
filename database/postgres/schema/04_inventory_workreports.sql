-- ---------------------------------------------------------------------
-- InventoryStockMovements (2026-06-19 overhaul)
--   Immutable ledger written by the C# transactional inventory finalize/reverse orchestration
--   (service-refactor reimplementation of sp_InventoryStockMovements_ApplyForReport). The filtered
--   UNIQUE(line, movement type) index enforces idempotency: at most one usage and one reversal per line.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "InventoryStockMovements" (
    "InventoryStockMovementId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "InventoryItemId"            integer NOT NULL,
    "WorkReportInventoryItemId"  integer NULL,
    "QuantityDelta"              numeric(18, 3) NOT NULL,
    "MovementType"               varchar(30)  NOT NULL,
    "SourceType"                 varchar(50)  NULL,
    "SourceId"                   integer NULL,
    "UsageType"                  varchar(20)  NULL,
    "CreatedAt"                  timestamp(6) NOT NULL DEFAULT (now() at time zone 'utc'),
    "CreatedByUserId"            integer NULL,
    CONSTRAINT "FK_InventoryStockMovements_Item" FOREIGN KEY ("InventoryItemId") REFERENCES "InventoryItems" ("InventoryItemId"),
    CONSTRAINT "FK_InventoryStockMovements_ReportLine" FOREIGN KEY ("WorkReportInventoryItemId") REFERENCES "WorkReportInventoryItems" ("WorkReportInventoryItemId"),
    CONSTRAINT "FK_InventoryStockMovements_User" FOREIGN KEY ("CreatedByUserId") REFERENCES "Users" ("UserId"),
    CONSTRAINT "CK_InventoryStockMovements_NonZero" CHECK ("QuantityDelta" <> 0),
    CONSTRAINT "CK_InventoryStockMovements_Type" CHECK ("MovementType" IN ('ReportUsage', 'ReportReversal')),
    CONSTRAINT "CK_InventoryStockMovements_Sign" CHECK (
        ("MovementType" = 'ReportUsage' AND "QuantityDelta" < 0)
        OR ("MovementType" = 'ReportReversal' AND "QuantityDelta" > 0)
    ),
    CONSTRAINT "CK_InventoryStockMovements_UsageType" CHECK ("UsageType" IS NULL OR "UsageType" IN ('Sold', 'Installed', 'Used')),
    CONSTRAINT "CK_InventoryStockMovements_SourcePair" CHECK (
        ("SourceType" IS NULL AND "SourceId" IS NULL) OR ("SourceType" IS NOT NULL AND "SourceId" IS NOT NULL)
    ),
    CONSTRAINT "CK_InventoryStockMovements_ReportSource" CHECK (
        "SourceType" IS NULL OR ("SourceType" = 'WorkReport' AND "WorkReportInventoryItemId" IS NOT NULL AND "UsageType" IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_InventoryStockMovements_Line_Type"
    ON "InventoryStockMovements" ("WorkReportInventoryItemId", "MovementType")
    WHERE ("WorkReportInventoryItemId" IS NOT NULL);
CREATE INDEX IF NOT EXISTS "IX_InventoryStockMovements_Source"
    ON "InventoryStockMovements" ("SourceType", "SourceId", "InventoryStockMovementId");
CREATE INDEX IF NOT EXISTS "IX_InventoryStockMovements_Item"
    ON "InventoryStockMovements" ("InventoryItemId", "InventoryStockMovementId");
