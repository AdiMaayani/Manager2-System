CREATE TABLE IF NOT EXISTS "WorkReportInventoryItems" (
    "WorkReportInventoryItemId" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkReportId"              integer NOT NULL,
    "InventoryItemId"          integer NOT NULL,
    "Quantity"                 numeric(18, 3) NOT NULL,
    "UsageType"                varchar(20)  NOT NULL,
    "SkuSnapshot"              varchar(50)  NOT NULL,
    "ItemNameSnapshot"         varchar(200) NOT NULL,
    "CreatedAt"                timestamp(6) NOT NULL DEFAULT (now() at time zone 'utc'),
    "CreatedByUserId"          integer NULL,
    CONSTRAINT "FK_WorkReportInventoryItems_Report" FOREIGN KEY ("WorkReportId") REFERENCES "WorkReports" ("WorkReportId"),
    CONSTRAINT "FK_WorkReportInventoryItems_Item" FOREIGN KEY ("InventoryItemId") REFERENCES "InventoryItems" ("InventoryItemId"),
    CONSTRAINT "FK_WorkReportInventoryItems_User" FOREIGN KEY ("CreatedByUserId") REFERENCES "Users" ("UserId"),
    CONSTRAINT "CK_WorkReportInventoryItems_Quantity" CHECK ("Quantity" > 0),
    CONSTRAINT "CK_WorkReportInventoryItems_UsageType" CHECK ("UsageType" IN ('Sold', 'Installed', 'Used')),
    CONSTRAINT "UQ_WorkReportInventoryItems_Report_Item_Usage" UNIQUE ("WorkReportId", "InventoryItemId", "UsageType")
);

CREATE INDEX IF NOT EXISTS "IX_WorkReportInventoryItems_Item"
    ON "WorkReportInventoryItems" ("InventoryItemId", "WorkReportId");

